package abc.abc343

fun main() {
    var i = 0L
    val n = readln().toLong()
    var ans = 0L
    while (i * i * i <= n) {
        val t = i.toString()
        if (t == t.reversed()) ans = i * i * i
        i++
    }
    println(ans)
}


@Suppress("unused")
private fun chmin(a: IntArray, idx: Int, v: Int): Boolean {
    if (v < a[idx]) {
        a[idx] = v
        return true
    }
    return false
}

